import { Easing } from 'remotion';

/**
 * РИТМ — базовая тайминговая грамматика. Часть ЯДРА: длительности входа, паузы,
 * характер торможения одинаково нужны любому стилю.
 *
 * Стиль-пак может переопределить ритм (например, пиксель-арт: ступенчатое
 * движение, никаких плавных кривых) — см. `style/index.ts`, поле `timing`.
 *
 * Все значения — в КАДРАХ. Движение всегда считается от useCurrentFrame().
 */

// ── ДЛИТЕЛЬНОСТИ ФАЗ (в кадрах @30fps) ─────────────────
