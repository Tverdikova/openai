import type React from 'react';

/**
 * КОНТРАКТ СТИЛЬ-ПАКА — граница между ядром и стилем.
 *
 * Ядро знает про стиль ровно столько, сколько описано здесь, и ни байтом больше.
 * Поэтому один и тот же движок собирает и голографическую инфографику, и
 * пиксельный мультик: меняется стиль-пак, ядро не трогается.
 *
 * Обязательный минимум — то, без чего ядро не может отрисовать даже строку текста.
 * Всё остальное (свечения, стёкла, текстуры, палитра спрайтов) стиль кладёт в
 * свободную секцию `extra` и пользуется этим внутри своих сцен как хочет.
 */

/** Описание одного уровня типографики. */
export interface TypeStep {
  /** Кегль в пикселях кадра. */
  size: number;
  weight: number;
  /** Межстрочный интервал, множитель. */
  lh: number;
  /** Межбуквенный интервал, css-значение. */
  ls: string;
  /** CSS font-family. */
  family: string;
  /** Капс ли этот уровень по умолчанию. */
  uppercase?: boolean;
}

/** Обязательные уровни типографики. Стиль может добавить свои сверху. */
export interface TypeScale {
  /** Главная фраза кадра. */
  hero: TypeStep;
  /** Запасной, более узкий уровень для длинных фраз. */
  heroTight: TypeStep;
  /** Подзаголовок, вторая строка. */
  title: TypeStep;
  /** Крупное число. */
  stat: TypeStep;
  /** Мелкая метка, тег, подпись. */
  label: TypeStep;
  /** Обычный текст. */
  body: TypeStep;
  [key: string]: TypeStep;
}

export interface StyleTokens {
  /** Имя стиля — показывается человеку, попадает в отчёты. */
  name: string;

  /** Обязательный минимум цветов. Всё остальное — в extra. */
  color: {
    /** Основной цвет текста. */
    text: string;
    /** Приглушённый текст. */
    textMuted: string;
    /** Базовый фон кадра. */
    bg: string;
    /** Акцент — им подсвечивается главное. */
    accent: string;
    [key: string]: string;
  };

  type: TypeScale;

  /** Скругления. Пиксель-арт ставит сюда нули — это нормально. */
  radius: { [key: string]: number };

  /** Базовый зазор между элементами. */
  space: { gap: number; [key: string]: number };

  /**
   * Свободная секция стиля. Ядро сюда не заглядывает.
   * Здесь живут свечения, границы стекла, текстуры, размер пикселя, палитры —
   * всё, что имеет смысл только внутри конкретного визуального языка.
   */
  extra?: Record<string, unknown>;
}

/** Переопределение ритма стилем. Любое поле необязательно. */
export interface StyleTiming {
  /**
   * Ступенчатость движения. Не задано или 0 — движение непрерывное.
   * 8 — восемь ступеней на такт: пиксель-арт, стоп-моушен, анимация «на двойках».
   */
  steps?: number;
  /** Множитель всех длительностей входа: 1.4 — стиль медленнее базового. */
  tempo?: number;
}

/**
 * Что стиль-пак обязан экспортировать из `style/index.ts`.
 * Если чего-то не хватает — сборка падает сразу, а не в середине рендера.
 */
export interface StylePack {
  tokens: StyleTokens;
  /** Неподвижная подложка кадра: фон, сетка, текстура, виньетка. */
  Background: React.FC;
  /**
   * Всегда-живой слой поверх фона. Гарантия, что даже пустой кадр не статичен.
   * Стиль решает сам, чем именно он живёт: пыль, помехи, дождь, рябь.
   */
  Ambient: React.FC;
  /** Загрузка шрифтов стиля. Кадры не рендерятся, пока шрифты не готовы. */
  FontLoader: React.FC<{ children: React.ReactNode }>;
  timing?: StyleTiming;
}
